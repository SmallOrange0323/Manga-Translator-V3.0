// 建立單字預編譯查表（排除一簡多繁容易誤傷正體字的單字，這些已由 PHRASE_REPLACEMENTS 處理）
const AMBIGUOUS_SINGLE_CHARS = new Set([
  '后', '发', '里', '干', '系', '面', '只', '脏', '松', '钟', '准', '台', '表', '困', '回', '借', '制', '致', '折', '症', '征', '余', '舍', '沈', '叶', '云', '谷', '克', '了'
]);

const CHAR_MAP = Object.create(null);
for (const pair of CN_TO_TW_PAIRS) {
  if (pair.length === 2) {
    const cn = pair[0];
    const tw = pair[1];
    if (cn !== tw && !AMBIGUOUS_SINGLE_CHARS.has(cn)) {
      CHAR_MAP[cn] = tw;
    }
  }
}

/**
 * 將含有簡體字或大陸慣用語的譯文轉換為台灣正統繁體中文（zh-TW）
 * @param {string} text
 * @returns {string}
 */
function convertCharacters(result) {
  let chars = null;
  const len = result.length;
  for (let i = 0; i < len; i++) {
    const ch = result[i];
    const mapped = CHAR_MAP[ch];
    if (mapped) {
      if (!chars) {
        chars = result.split('');
      }
      chars[i] = mapped;
    }
  }

  return chars ? chars.join('') : result;
}

const SORTED_PHRASES = [...PHRASE_REPLACEMENTS].sort((a, b) => b[0].length - a[0].length);
// Normalize keys with the same protected character map to match Traditional
// Chinese and mixed input, while retaining phrase-level ambiguous characters.
const TRADITIONAL_PHRASES = SORTED_PHRASES.map(([src, dst]) => [convertCharacters(src), dst]);

function replacePhrases(text, phrases) {
  let result = text;
  for (const [src, dst] of phrases) {
    if (src !== dst && result.includes(src)) result = result.split(src).join(dst);
  }
  return result;
}

export function convertCnToTwLocal(text) {
  if (!text || typeof text !== 'string') return text;
  const normalized = convertCharacters(replacePhrases(text, SORTED_PHRASES));
  return replacePhrases(normalized, TRADITIONAL_PHRASES);
}
